#!/usr/bin/env bash
set -euo pipefail
cd -- "$(dirname -- "${BASH_SOURCE[0]}")"
command -v docker >/dev/null || { echo '请先安装 Docker Engine 和 Docker Compose 插件。'; exit 1; }
docker compose version >/dev/null
docker info >/dev/null
if [[ ! -f .env ]]; then
  command -v openssl >/dev/null || { echo '请先安装 openssl。'; exit 1; }
  [[ -r /dev/tty ]] || { echo '首次配置需要终端。也可以自行复制 .env.example 为 .env 后重试。'; exit 1; }
  umask 077
  config_tmp=$(mktemp .env.setup.XXXXXX)
  trap 'rm -f -- "${config_tmp:-}"' EXIT
  printf '# Generated by setup.sh\n' > "$config_tmp"
  prompt() {
    local key=$1 label=$2 default=${3:-} secret=${4:-false} value
    while true; do
      printf '%s%s: ' "$label" "${default:+ [$default]}" >/dev/tty
      if [[ $secret == true ]]; then
        IFS= read -r -s value </dev/tty
        printf '\n' >/dev/tty
      else
        IFS= read -r value </dev/tty
      fi
      value=${value:-$default}
      [[ -n $value ]] || { echo '此项不能为空。' >/dev/tty; continue; }
      # Keep generated dotenv values literal and single-line.
      [[ $value != *"'"* && $value != *$'\r'* ]] || { echo '配置值不能包含单引号或回车。' >/dev/tty; continue; }
      if [[ $key == PUBLIC_URL && ! $value =~ ^https://[^/[:space:]]+(/[^[:space:]]*)?$ ]]; then
        echo '请输入公网 HTTPS 地址。' >/dev/tty; continue
      fi
      printf "%s='%s'\n" "$key" "$value" >> "$config_tmp"
      break
    done
  }
  prompt PUBLIC_URL '公网 HTTPS 地址（反代到 127.0.0.1:3000）'
  prompt ADMIN_USER '后台账号' admin
  prompt ADMIN_PASSWORD '后台密码' '' true
  prompt CRISP_ID 'Crisp Token Identifier'
  prompt CRISP_KEY 'Crisp Token Key' '' true
  prompt CRISP_SECRET 'Crisp Webhook 签名密钥' '' true
  prompt CRISP_URN 'Crisp 插件 URN'
  prompt TELEGRAM_TOKEN 'Telegram Bot Token' '' true
  prompt OPENAI_URL 'OpenAI 兼容 API 地址' https://api.openai.com/v1
  prompt OPENAI_KEY 'AI API Key' '' true
  prompt OPENAI_MODEL '聊天模型' gpt-4.1-nano
  printf "POSTGRES_PASSWORD='%s'\n" "$(openssl rand -hex 24)" >> "$config_tmp"
  mv -- "$config_tmp" .env
  trap - EXIT
fi
# Existing .env and database credentials are never regenerated.
docker compose up -d --build --wait --wait-timeout 180
printf '\n服务已启动。请将 HTTPS 域名反代到 127.0.0.1:3000，在后台创建项目。\n'
printf 'Crisp Webhook: https://你的域名/crisp；Telegram Webhook 会自动注册。\n'
